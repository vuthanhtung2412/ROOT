/**
 * Generate lib/src/cards/ep.generated.ts from resources/reference/ep-decks/cards.json
 *
 * Run: pnpm --filter @root/lib gen:cards
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const cardsPath = resolve(root, 'resources/reference/ep-decks/cards.json')
const outPath = resolve(root, 'lib/src/cards/ep.generated.ts')

type RawCard = {
  id: string
  name: string
  image: string
  suit: string
  type: string
  copies: number
  cost: string[]
  description: string
  item?: string
  vp?: number
}

const raw = JSON.parse(readFileSync(cardsPath, 'utf8')) as { cards: RawCard[] }

const lines: string[] = []
lines.push(`// Generated by lib/scripts/gen-cards.ts — do not edit by hand`)
lines.push(`import type { CardDef } from './types.js'`)
lines.push(``)
lines.push(`export const EP_CARD_DEFS: CardDef[] = [`)

for (const c of raw.cards) {
  const cost = JSON.stringify(c.cost)
  const item = c.item ? ` item: '${c.item}',` : ''
  const vp = c.vp !== undefined ? ` vp: ${c.vp},` : ''
  lines.push(`  {`)
  lines.push(`    defId: '${c.id}',`)
  lines.push(`    name: ${JSON.stringify(c.name)},`)
  lines.push(`    suit: '${c.suit}',`)
  lines.push(`    type: '${c.type}',`)
  lines.push(`    cost: ${cost},`)
  if (item) lines.push(`   ${item}`)
  if (vp) lines.push(`   ${vp}`)
  lines.push(`    description: ${JSON.stringify(c.description)},`)
  lines.push(`    image: ${JSON.stringify(c.image)},`)
  lines.push(`    copies: ${c.copies},`)
  lines.push(`  },`)
}

lines.push(`]`)
lines.push(``)

writeFileSync(outPath, lines.join('\n'))
console.log(`wrote ${outPath} (${raw.cards.length} defs)`)
