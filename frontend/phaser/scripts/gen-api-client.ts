/**
 * Generate Phaser OpenAPI types from the Hono `/doc` (or a dumped openapi.json).
 *
 * Run from repo root:
 *   pnpm gen:api-client
 *   pnpm --filter @root/phaser gen:api-client
 *
 * Sources (first hit wins):
 *   1. OPENAPI_PATH — path to an OpenAPI JSON file
 *   2. backend/web/openapi.json — dumped by `pnpm --filter @root/web gen:openapi`
 *   3. ROOT_API/doc (default http://localhost:3000/doc) — live Hono OpenAPI route
 *
 * Output: frontend/phaser/src/api/generated/schema.d.ts
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTypescript from 'openapi-typescript'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(scriptDirectory, '../../..')
const defaultOpenApiDumpPath = resolve(repositoryRoot, 'backend/web/openapi.json')
const outputDirectory = resolve(scriptDirectory, '../src/api/generated')
const outputPath = resolve(outputDirectory, 'schema.d.ts')
const defaultDocumentationUrl = `${process.env.ROOT_API ?? 'http://localhost:3000'}/doc`

async function resolveOpenApiSource(): Promise<{ label: string; absolutePath: string }> {
  const explicitPath = process.env.OPENAPI_PATH
  if (explicitPath) {
    const absolutePath = resolve(explicitPath)
    if (!existsSync(absolutePath)) {
      throw new Error(`OPENAPI_PATH not found: ${absolutePath}`)
    }
    return { label: absolutePath, absolutePath }
  }

  if (existsSync(defaultOpenApiDumpPath)) {
    return { label: defaultOpenApiDumpPath, absolutePath: defaultOpenApiDumpPath }
  }

  const documentationUrl = process.env.OPENAPI_URL ?? defaultDocumentationUrl
  const nextSteps = [
    'Start @root/web with OpenAPI `/doc`, or dump the spec first:',
    '  pnpm --filter @root/web gen:openapi',
    'Then re-run: pnpm gen:api-client',
  ]
  let response: Response
  try {
    response = await fetch(documentationUrl)
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error)
    throw new Error([`Failed to fetch OpenAPI from ${documentationUrl} (${detail})`, ...nextSteps].join('\n'))
  }
  if (!response.ok) {
    throw new Error(
      [`Failed to fetch OpenAPI from ${documentationUrl} (${response.status})`, ...nextSteps].join('\n'),
    )
  }
  const body = await response.text()
  JSON.parse(body)
  mkdirSync(dirname(defaultOpenApiDumpPath), { recursive: true })
  writeFileSync(defaultOpenApiDumpPath, body)
  return { label: documentationUrl, absolutePath: defaultOpenApiDumpPath }
}

async function main(): Promise<void> {
  const source = await resolveOpenApiSource()
  const spec = JSON.parse(readFileSync(source.absolutePath, 'utf8')) as Parameters<
    typeof openapiTypescript
  >[0]
  const generated = await openapiTypescript(spec)
  mkdirSync(outputDirectory, { recursive: true })
  const banner = [
    '// Generated by frontend/phaser/scripts/gen-api-client.ts — do not edit by hand',
    `// Source: ${source.label}`,
    '',
  ].join('\n')
  writeFileSync(outputPath, `${banner}${generated}`)
  console.log(`wrote ${outputPath}`)
  console.log(`source ${source.label}`)
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
